def generate_recommendations(component, patterns, exploit_prediction):
    """Generate security recommendations for a component"""
    recommendations = []
    
    # Version update recommendations
    if patterns['risk_level'] == 'high':
        recommendations.append({
            'type': 'version_update',
            'priority': 'critical',
            'description': f"Update {component['name']} to latest secure version",
            'details': 'Critical vulnerabilities detected'
        })
    
    # Security control recommendations
    if exploit_prediction['exploit_probability'] > 0.7:
        recommendations.append({
            'type': 'security_control',
            'priority': 'high',
            'description': 'Implement additional security controls',
            'details': exploit_prediction['explanation']['key_factors']
        })
    
    # Architecture recommendations
    if patterns.get('code_analysis', {}).get('risk_level') == 'high':
        recommendations.append({
            'type': 'architecture',
            'priority': 'medium',
            'description': 'Consider architectural changes to reduce risk exposure',
            'details': patterns['code_analysis'].get('recommendations', [])
        })
    
    return recommendations

def calculate_overall_risk(components):
    """Calculate overall risk score"""
    if not components:
        return 0.0
    
    # Weight factors
    weights = {
        'risk_score': 0.3,
        'exploit_probability': 0.3,
        'cvss_max_score': 0.2,
        'vulnerability_count': 0.2
    }
    
    total_score = 0.0
    for comp in components:
        component_score = (
            comp['threat_analysis']['risk_score'] * weights['risk_score'] +
            comp['threat_analysis']['exploit_probability'] * weights['exploit_probability'] +
            (comp['security_metrics']['cvss_max_score'] / 10.0) * weights['cvss_max_score'] +
            min(comp['security_metrics']['vulnerability_count'] / 5.0, 1.0) * weights['vulnerability_count']
        )
        total_score = max(total_score, component_score)
    
    return total_score

def prioritize_recommendations(recommendations):
    """Prioritize and deduplicate recommendations"""
    priority_order = {'critical': 0, 'high': 1, 'medium': 2, 'low': 3}
    
    # Sort by priority
    sorted_recs = sorted(
        recommendations,
        key=lambda x: priority_order.get(x['priority'], 999)
    )
    
    # Deduplicate while preserving order
    seen = set()
    unique_recs = []
    for rec in sorted_recs:
        key = (rec['type'], rec['description'])
        if key not in seen:
            seen.add(key)
            unique_recs.append(rec)
    
    return unique_recs

