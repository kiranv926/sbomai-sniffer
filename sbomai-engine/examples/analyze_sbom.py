def analyze_sbom(sbom_data):
    """Run comprehensive SBOM analysis"""
    print("\n=== SBOMAI Engine Analysis ===")
    print(f"Analyzing SBOM generated by {sbom_data['metadata']['tool']}")
    print(f"Timestamp: {sbom_data['metadata']['timestamp']}")
    
    # Initialize analyzers
    threat_analyzer = ThreatContextEmbedding()
    pattern_detector = ExploitPatternDetector()
    exploit_predictor = ExploitPredictor()
    
    results = {
        'components': [],
        'overall_risk_score': 0.0,
        'critical_components': [],
        'security_recommendations': []
    }
    
    # Analyze each component
    for component in sbom_data['components']:
        print(f"\n--- Analyzing {component['name']} {component['version']} ---")
        
        # 1. Threat Context Analysis
        component_data = enrich_component_data(component)
        threat_context = threat_analyzer.embed_component(component_data)
        
        # 2. Pattern Detection
        patterns = pattern_detector.analyze_component(component_data)
        
        # 3. Exploit Prediction
        exploit_prediction = exploit_predictor.predict_exploit_likelihood(
            component_data['vulnerability_data']
        )
        
        # Combine results
        component_analysis = {
            'name': component['name'],
            'version': component['version'],
            'purl': component['purl'],
            'threat_analysis': {
                'risk_score': threat_context['risk_score'],
                'detected_patterns': patterns['pattern_matches'],
                'exploit_probability': exploit_prediction['exploit_probability'],
                'vulnerabilities': component_data['vulnerability_data']['vulnerabilities']
            },
            'security_metrics': {
                'cvss_max_score': max([v['cvss_score'] for v in component_data['vulnerability_data']['vulnerabilities']], default=0.0),
                'vulnerability_count': len(component_data['vulnerability_data']['vulnerabilities']),
                'exploit_confidence': exploit_prediction['confidence_score']
            },
            'recommendations': generate_recommendations(
                component,
                patterns,
                exploit_prediction
            )
        }
        
        results['components'].append(component_analysis)
        
        # Track critical components
        if component_analysis['threat_analysis']['risk_score'] > 0.7:
            results['critical_components'].append({
                'name': component['name'],
                'version': component['version'],
                'risk_score': component_analysis['threat_analysis']['risk_score'],
                'critical_vulnerabilities': [
                    v for v in component_data['vulnerability_data']['vulnerabilities']
                    if v['severity'] == 'CRITICAL'
                ]
            })
    
    # Calculate overall risk score
    results['overall_risk_score'] = calculate_overall_risk(results['components'])
    
    # Generate security recommendations
    results['security_recommendations'] = prioritize_recommendations(
        [rec for comp in results['components'] for rec in comp['recommendations']]
    )
    
    return results

